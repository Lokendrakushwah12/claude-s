"""Word-level lyric timings + beat grid for a song -> lyrics.js.

    uv run align.py song.mp3 [lyrics.txt]

lyrics.txt (the real lyrics, one line per line) is optional but strongly recommended: it primes
Whisper so the words come out right. Sung vocals still mis-transcribe sometimes, so always read
lyrics.js afterwards and fix any wrong words by hand (keep the timings).
WHISPER_MODEL=large-v3 is more accurate but slower; default is medium.
"""
import json, os, sys

import librosa
import numpy as np
from faster_whisper import WhisperModel

song = sys.argv[1]
prompt = open(sys.argv[2]).read() if len(sys.argv) > 2 else None

model = WhisperModel(os.environ.get("WHISPER_MODEL", "medium"), device="cpu", compute_type="int8")
segs, _ = model.transcribe(song, word_timestamps=True, initial_prompt=prompt, condition_on_previous_text=False)
lines = [{"start": round(s.start, 2), "end": round(s.end, 2), "text": s.text.strip(),
          "words": [{"w": w.word.strip(), "s": round(w.start, 2), "e": round(w.end, 2)} for w in s.words]}
         for s in segs]

y, sr = librosa.load(song, sr=22050, mono=True)
tempo, frames = librosa.beat.beat_track(y=y, sr=sr)
tempo = float(np.ravel(tempo)[0])
beats = [round(float(b), 3) for b in librosa.frames_to_time(frames, sr=sr)]
duration = round(len(y) / sr, 2)

with open("lyrics.js", "w") as f:
    f.write(f"// generated by align.py from {os.path.basename(song)}; fix words by hand, keep timings\n")
    f.write(f"window.SONG = {json.dumps({'duration': duration, 'bpm': round(tempo, 1)})};\n")
    f.write("window.LYRICS = [\n" + ",\n".join("  " + json.dumps(l, ensure_ascii=False) for l in lines) + "\n];\n")
    f.write(f"window.BEATS = {json.dumps(beats)};\n")
print(f"{duration}s, {tempo:.0f} bpm, {len(lines)} lines, {len(beats)} beats -> lyrics.js")
